function clipAtWord(value, max) {
  const text = String(value || "").trim();
  if (!text) return "";
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const lastSpace = cut.lastIndexOf(" ");
  return (lastSpace > 18 ? cut.slice(0, lastSpace) : cut).trim();
}

export function socialCopyFor(slug, fallback = {}) {
  const curated = BLOG_SOCIAL_COPY[slug];
  if (curated) return curated;
  return {
    socialTitle: clipAtWord(fallback.title, 42),
    socialHook: clipAtWord(fallback.excerpt || fallback.description, 160),
  };
}
